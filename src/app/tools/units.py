"""Перевод измерений в СИ.

Зачем. Формула в методичке записана в СИ, а студент пишет в журнал то, что
показывает прибор: удлинение в миллиметрах, массу в граммах, время в
минутах. Умножать такие числа на формулу СИ нельзя: модуль Юнга по
удлинению в миллиметрах выходит ровно в тысячу раз меньше, и ни
размерность, ни порядок этого не выдают — ошибка выглядит как результат.
Раньше расчётчик печатал подставленные величины и просил студента сверить
единицы сам; теперь он их переводит, а печатает то, что перевёл.

Как. Единица опознаётся по точному совпадению с таблицей ниже, а не по
приставке: «мН» — это и миллиньютон, и меганьютон, и угадывать здесь
нельзя. Нераспознанная единица остаётся как есть, и об этом говорится в
ответе — молчаливое «считаю, что это СИ» было бы тем самым, от чего
перевод и защищает.

Множитель и сдвиг. Почти все переводы — умножение, но температура в
градусах Цельсия переводится сдвигом на 273.15, и без него «n = p/(k*T)»
даёт при 20 °C ошибку в пятнадцать раз. Погрешность при сдвиге не меняется
(разность температур одна и та же в кельвинах и в градусах), поэтому она
умножается только на множитель.

Что этот модуль не делает. Размерность результата не считается: мы не
знаем, что получается из `L/(S*k)`, и приписать ответу «Па» не можем.
Сказать можно только то, что известно точно: всё, что вошло в расчёт,
приведено к СИ, значит и результат в СИ.
"""

