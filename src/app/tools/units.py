TRIM_RE = re.compile(r"[\s.,·\[\]()]+")


def normalize(unit: str) -> str:
    """Единица в виде ключа таблицы: «мм рт. ст.» → «ммртст»."""
    return TRIM_RE.sub("", (unit or "").strip().lower())


@dataclass
class Conversion:
    """Перевод одной величины в СИ."""

    name: str  # столбец или заданная величина
    unit: str  # как написал студент
    si_unit: str  # единица СИ
    factor: float = 1.0
    offset: float = 0.0

    @property
    def changes_anything(self) -> bool:
        return self.factor != 1.0 or self.offset != 0.0

    @property
    def as_text(self) -> str:
        if self.offset:
            return f"{self.name} из {self.unit} в {self.si_unit} (+{self.offset:g})"
        return f"{self.name} из {self.unit} в {self.si_unit} (×{self.factor:g})"


def to_si(unit: str) -> tuple[str, float, float] | None:
    """(единица СИ, множитель, сдвиг) или None для незнакомой единицы."""
    text = normalize(unit)
    known = UNITS.get(text)
    if known is not None:
        return known
    # Powers apply to the conversion factor as well: ms² -> 10^-6 s².
    power = re.fullmatch(r"(.+?)(?:\^?([23])|([²³]))", text)
    if power:
        base = UNITS.get(power.group(1))
        if base is not None and base[2] == 0:
            exponent = int(power.group(2) or {"²": "2", "³": "3"}[power.group(3)])
            canonical = base[0]
            # Do not multiply powers on already composite units implicitly.
            if re.fullmatch(r"[A-Za-zА-Яа-я]+", canonical):
                return canonical + {2:"²",3:"³"}[exponent], base[1]**exponent, 0.0
    return None


def convert(value: float, factor: float, offset: float = 0.0) -> float:
    return value * factor + offset


def convert_columns(
    columns: dict[str, list[float]], units: dict[str, str]
) -> tuple[dict[str, list[float]], dict[str, str], list[Conversion], list[str]]:
    """Столбцы в СИ.

    Возвращает переведённые столбцы, их единицы, список выполненных
    переводов и имена столбцов с незнакомой единицей — о последних
    расчётчик обязан сказать студенту: там он продолжает считать как есть.
    """
    converted: dict[str, list[float]] = {}
    si_units: dict[str, str] = {}
    done: list[Conversion] = []
    unknown: list[str] = []
    for name, values in columns.items():
        unit = units.get(name, "")
        known = to_si(unit) if unit else None
        if known is None:
            converted[name] = list(values)
            si_units[name] = unit
            if unit:
                unknown.append(f"{name} [{unit}]")
            continue
        si_unit, factor, offset = known
        converted[name] = [convert(value, factor, offset) for value in values]
        si_units[name] = si_unit
        step = Conversion(
            name=name, unit=unit, si_unit=si_unit, factor=factor, offset=offset
        )
        if step.changes_anything:
            done.append(step)
    return converted, si_units, done, unknown
